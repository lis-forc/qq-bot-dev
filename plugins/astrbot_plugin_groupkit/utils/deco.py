"""表情记号（emoji）。

**为什么只在标题行用。**
这个插件有一批纯文字回复（口令清单、额度记录、排行榜），靠 `text.py` 的
`width()` 补空格对齐。emoji 的显示宽度由客户端字体决定（多数当成两个半角位，
少数当成一个），`width()` 只能按 Unicode 区块猜，猜错一格整列就歪。所以规矩定死：

    emoji 只许出现在「行首标题」和「行尾收束」，**不许进表格单元格**。

这样它只是个记号，不参与任何对齐计算，怎么加都不会把表弄歪。

**为什么不随机。**
同一个命令每次给不同的表情，会让人以为「这次的结果和上次不一样」。
所以按用途固定：看到 💰 就知道是额度那一类。

**选字标准：只用高频 emoji。**
emoji 缺字形时客户端会画成一个空心方块（俗称豆腐块）。缺不缺取决于客户端
字体覆盖到哪一版 Unicode —— 🔥 💰 📊 🛒 这类几乎每个字体都收录，
而 🎟 🏷 ☒ 这类冷僻符号经常没有。所以这里只挑最常用的那批：
宁可用得平淡，也不要在别人手机上变成一串方块。
"""

from __future__ import annotations

# 按用途固定，不随机。键名是「这条回复在讲什么」，不是「哪个功能」。
MARKS: dict[str, str] = {
    "base": "🔥",      # 日常口令总目录：最常用的一组
    "checkin": "📅",   # 签到：一天一格
    "fortune": "✨",   # 今日运势：闪一下
    "quota": "💰",     # 额度：钱
    "stats": "📊",     # 统计：在看数字
    "profile": "👤",   # 个人信息卡：一个人
    "nick": "🦊",      # 昵称与记号：就是那个性别记号本身
    "shop": "🛒",      # 商店：推个车挑东西
    "service": "💳",   # 付费服务（自由人这类买断制的东西）
    "titles": "🏆",    # 称号：奖杯
    "draw": "🎲",      # 抽奖：掷骰子
    "meme": "😄",      # 表情包：笑脸
    "fun": "🎨",       # 娱乐页页头：在画东西
    "level": "🔑",     # 权限分级：钥匙
    "search": "🔍",    # 翻查类：在目录里找
    "edit": "📝",      # 改资料：动笔
    "join": "👋",      # 入群：招手
    "verify": "🔐",    # 入群验证：过关
    "admin": "👮",     # 群管：盯着你
    "ok": "✅",        # 成功
    "data": "📦",      # 数据保留：装箱
    "meh": "⚠️",       # 出错 / 没有
    "card": "🪪",      # 名片皮肤
    "bag": "🎒",       # 背包：装消耗品
    "relations": "💕", # 关系：结缔
}

# 排行榜前三名的序号。单独一张表，因为它们只有「位置」这一个含义，
# 和上面那批「用途」记号不是一回事。
MEDALS: tuple[str, str, str] = ("🥇", "🥈", "🥉")


def medal(rank: int) -> str:
    """第几名 → 奖牌；第四名之后给普通的 `N.`。"""
    if 1 <= rank <= len(MEDALS):
        return MEDALS[rank - 1]
    return f"{rank}."

# 没有任何记号时的兜底
DEFAULT = "🔸"


def mark(key: str) -> str:
    """取一个记号。键不认识就给兜底，绝不抛异常 —— 这只是排版装饰。"""
    return MARKS.get(key, DEFAULT)


def head(text: str, key: str) -> str:
    """行首：`💰 额度记录`。"""
    return f"{mark(key)} {text}"


def tail(text: str, key: str) -> str:
    """行尾：`额度记录 💰`。用于标题已经带了括号/方框的情况。"""
    return f"{text} {mark(key)}"
